/**
 * Regenerate the committed client mirror from the host capability-hints table.
 *
 * The single authored source is
 * `profile/web/packages/enpoi-provider-sync/model-capability-hints.json`,
 * loaded by the sync at runtime. The browser bundle cannot import this
 * package's tree, so this script writes two committed artifacts:
 *
 * - `packages/client/ui-settings-models/src/client/model-capability-hints.generated.ts`
 *   (the typed table the provider detail panel loads), and
 * - `packages/client/ui-settings-models/tests/expected/model-capability-hints.json`
 *   (the parity fixture the sync package's spec reads by path).
 *
 * Two specs keep the mirror honest: the sync package's
 * `tests/capability-hints.spec.ts` pins the fixture to the host JSON, and
 * `packages/client/ui-settings-models/tests/model-capability-hints.client.spec.ts`
 * pins the generated module to the same fixture. Drift on either side fails a
 * suite.
 *
 * Run from the repository root after any table change:
 *
 *   node profile/web/packages/enpoi-provider-sync/scripts/write-client-mirror.mjs
 *
 * `--check` writes nothing and exits non-zero on drift (usable as a gate).
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const source = join(here, '..', 'model-capability-hints.json')
const modulePath = join(here, '../../../../../packages/client/ui-settings-models/src/client/model-capability-hints.generated.ts')
const fixturePath = join(here, '../../../../../packages/client/ui-settings-models/tests/expected/model-capability-hints.json')

const FAMILIES = ['reasoning', 'image', 'audio', 'video', 'files', 'toolsExclude']

const table = JSON.parse(readFileSync(source, 'utf8'))
for (const family of FAMILIES) {
  if (!Array.isArray(table[family]) || table[family].some(operand => typeof operand !== 'string' || operand.length === 0)) {
    console.error(`capability hints ${source}: "${family}" must be a list of non-empty id substrings`)
    process.exit(1)
  }
}

/** The authored table projection the client mirror carries. */
const projection = {
  version: table.version,
  ...Object.fromEntries(FAMILIES.map(family => [family, table[family]])),
}
const nextFixture = `${JSON.stringify(projection, null, 2)}\n`

const moduleSource = [
  '/**',
  ' * The shared model-capability id-heuristic table, generated from',
  ' * profile/web/packages/enpoi-provider-sync/model-capability-hints.json.',
  ' *',
  ' * GENERATED by profile/web/packages/enpoi-provider-sync/scripts/write-client-mirror.mjs',
  ' * — do not edit by hand; run the script after a table change. The table is',
  ' * hints only: the sync persists a hinted capability under `capabilityHints`,',
  ' * never as a disclosed fact.',
  ' */',
  '',
  '/** The shipped id-heuristic operand table. Every list holds lowercase id substrings. */',
  'export interface ModelCapabilityHints {',
  ...FAMILIES.map(family => `  readonly ${family}: readonly string[]`),
  '}',
  '',
  '/** The generated mirror of the shipped `model-capability-hints.json`. */',
  'export const MODEL_CAPABILITY_HINTS: ModelCapabilityHints = {',
]
for (const family of FAMILIES) {
  moduleSource.push(`  ${family}: [`)
  for (const operand of table[family]) moduleSource.push(`    ${JSON.stringify(operand)},`)
  moduleSource.push('  ],')
}
moduleSource.push('}', '')
const nextModule = moduleSource.join('\n')

const targets = [
  { path: modulePath, content: nextModule },
  { path: fixturePath, content: nextFixture },
]

if (process.argv.includes('--check')) {
  let stale = false
  for (const target of targets) {
    let current = ''
    try {
      current = readFileSync(target.path, 'utf8')
    } catch {
      current = ''
    }
    if (current !== target.content) {
      console.error(`capability-hints client mirror is stale: ${target.path}`)
      stale = true
    }
  }
  if (stale) process.exit(1)
  console.log('capability-hints client mirror is current')
} else {
  for (const target of targets) {
    writeFileSync(target.path, target.content, 'utf8')
    console.log(`wrote ${target.path}`)
  }
}
